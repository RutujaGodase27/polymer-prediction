import streamlit as st
import pandas as pd
import numpy as np
import joblib

# Page configuration
st.set_page_config(
    page_title="AI Polymer Prediction",
    page_icon="🧪",
    layout="wide"
)

# Load trained model
bundle = joblib.load("model_bundle.joblib")

model = bundle["model"]
features = bundle["features"]
minimums = bundle["minimums"]
maximums = bundle["maximums"]

# Estimate medians for fallback if not saved directly
medians = {f: (minimums[f] + maximums[f]) / 2 for f in features}

# Website heading
st.title("🧪 AI Polymer Identification System")

st.write(
    "Enter the property ranges of a material "
    "to identify the most likely polymer."
)

st.info(
    "Select the properties you want to use. "
    "Enter a minimum and maximum value for each."
)

st.divider()

# Input section
st.header("Material Property Inputs")

selected_ranges = {}

# Display all properties in two columns
col1, col2 = st.columns(2)

for i, feature in enumerate(features):
    container = col1 if i % 2 == 0 else col2
    with container:
        st.subheader(feature)
        use_property = st.checkbox(
            f"Use {feature}",
            key=f"use_{feature}"
        )

        if use_property:
            low = float(minimums[feature])
            high = float(maximums[feature])

            min_value = st.number_input(
                "Minimum value",
                value=low,
                key=f"min_{feature}"
            )

            max_value = st.number_input(
                "Maximum value",
                value=high,
                key=f"max_{feature}"
            )

            if min_value > max_value:
                st.error("Minimum cannot exceed maximum.")
            else:
                selected_ranges[feature] = (min_value, max_value)

# Prediction section
st.divider()

if st.button("🔍 Predict Polymer", type="primary"):
    if not selected_ranges:
        st.warning("Please select at least one property.")
    else:
        invalid = any(low > high for low, high in selected_ranges.values())
        if invalid:
            st.error("Please correct your property ranges.")
        else:
            # Generate input combinations
            np.random.seed(42)
            number_of_samples = 200

            input_data = pd.DataFrame(
                {
                    feature: np.full(
                        number_of_samples,
                        float(medians[feature])
                    )
                    for feature in features
                }
            )

            # Apply selected ranges
            for feature, (low, high) in selected_ranges.items():
                input_data[feature] = np.random.uniform(low, high, number_of_samples)

            # Predict materials
            probabilities = model.predict_proba(input_data)
            classes = model.named_steps["classifier"].classes_

            # Average model probabilities
            average_scores = probabilities.mean(axis=0)

            results = pd.DataFrame({
                "Polymer / Material": classes,
                "Estimated Match (%)": average_scores * 100
            })

            results = results.sort_values(
                "Estimated Match (%)",
                ascending=False
            ).reset_index(drop=True)

            # Display result
            st.success("Prediction completed!")
            st.header("Prediction Results")

            best = results.iloc[0]
            st.subheader("Most Likely Material")
            st.title(best["Polymer / Material"])

            st.metric(
                "Estimated Match Score",
                f"{best['Estimated Match (%)']:.2f}%"
            )

            st.caption(
                "This score is the average model probability "
                "over generated combinations within your "
                "selected ranges. It is not a guarantee "
                "or a validated real-world probability."
            )

            # Top 5 alternatives
            st.subheader("Top Matching Materials")
            st.dataframe(
                results.head(5),
                use_container_width=True
            )

            # Graph
            st.subheader("Material Prediction Comparison")
            st.bar_chart(
                results.head(5).set_index("Polymer / Material")
            )

            # Download results
            csv = results.to_csv(index=False)
            st.download_button(
                "Download Prediction Results",
                data=csv,
                file_name="polymer_predictions.csv",
                mime="text/csv"
            )

st.divider()
st.caption(
    "AI-Based Polymer Identification and "
    "Material Property Prediction Project"
)
