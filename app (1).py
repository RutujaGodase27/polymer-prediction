# ==========================================================
# ADVANCED MATERIAL PROPERTY PREDICTION MODEL
# Multiple Algorithms + Hyperparameter Tuning
# ==========================================================

import pandas as pd
import numpy as np
import joblib

from sklearn.model_selection import (
    train_test_split,
    RandomizedSearchCV,
    StratifiedKFold
)

from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.feature_selection import VarianceThreshold

from sklearn.ensemble import (
    RandomForestClassifier,
    ExtraTreesClassifier,
    HistGradientBoostingClassifier,
    RandomForestRegressor
)

from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix
)

# ==========================================================
# 1. LOAD DATASET
# ==========================================================

# Updated path to point to the correct file location
df = pd.read_excel("/content/PolymerAI_MultiProperty_Dataset (3).xlsx", header=1)

target = "Family"

df = df.dropna(subset=[target]).copy()

# Select numerical properties
X = df.select_dtypes(include=np.number).copy()

# Remove constant columns
X = X.loc[:, X.nunique(dropna=True) > 1]

y = df[target].astype(str)

print("Dataset Shape:", df.shape)
print("Number of Properties:", len(X.columns))
print("Number of Materials:", y.nunique())

print("\nMaterial Distribution:")
print(y.value_counts())

# ==========================================================
# 2. TRAIN TEST SPLIT
# ==========================================================

if y.value_counts().min() < 2:
    raise ValueError(
        "Some material classes have fewer than 2 records. "
        "Add more data for reliable evaluation."
    )

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# ==========================================================
# 3. CREATE PIPELINE
# ==========================================================

pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("variance", VarianceThreshold()),
    ("classifier", RandomForestClassifier(random_state=42))
])

# ==========================================================
# 4. ALGORITHM AND PARAMETER SEARCH
# ==========================================================

parameter_grid = [

    # RANDOM FOREST
    {
        "classifier": [
            RandomForestClassifier(
                random_state=42,
                class_weight="balanced"
            )
        ],
        "classifier__n_estimators": [200, 300, 500, 700],
        "classifier__max_depth": [None, 10, 20, 30, 40],
        "classifier__min_samples_split": [2, 5, 10],
        "classifier__min_samples_leaf": [1, 2, 4],
        "classifier__max_features": ["sqrt", "log2", None]
    },

    # EXTRA TREES
    {
        "classifier": [
            ExtraTreesClassifier(
                random_state=42,
                class_weight="balanced"
            )
        ],
        "classifier__n_estimators": [200, 300, 500, 700],
        "classifier__max_depth": [None, 10, 20, 30, 40],
        "classifier__min_samples_split": [2, 5, 10],
        "classifier__min_samples_leaf": [1, 2, 4],
        "classifier__max_features": ["sqrt", "log2", None]
    }
]

# ==========================================================
# 5. CROSS VALIDATION
# ==========================================================

min_samples = y_train.value_counts().min()

cv = StratifiedKFold(
    n_splits=min(5, min_samples),
    shuffle=True,
    random_state=42
)

# ==========================================================
# 6. AUTOMATIC HYPERPARAMETER TUNING
# ==========================================================

search = RandomizedSearchCV(
    estimator=pipeline,
    param_distributions=parameter_grid,
    n_iter=50,
    scoring="accuracy",
    cv=cv,
    random_state=42,
    n_jobs=-1,
    verbose=1
)

print("\nTraining Started...")

search.fit(X_train, y_train)

best_model = search.best_estimator_

print("\nBest Algorithm:")
print(type(best_model.named_steps["classifier"]).__name__)

print("\nBest Cross Validation Accuracy:")
print(round(search.best_score_ * 100, 2), "%")

print("\nBest Parameters:")
print(search.best_params_)

# ==========================================================
# 7. TEST MODEL
# ==========================================================

predictions = best_model.predict(X_test)

accuracy = accuracy_score(y_test, predictions)

print("\n================================")
print("FINAL TEST ACCURACY")
print("================================")

print("Accuracy:", round(accuracy * 100, 2), "%")

print("\nCLASSIFICATION REPORT")

print(classification_report(
    y_test,
    predictions,
    zero_division=0
))

print("\nCONFUSION MATRIX")

print(confusion_matrix(y_test, predictions))

# ==========================================================
# 8. SAVE TRAINED MODEL
# ==========================================================

model_bundle = {
    "model": best_model,
    "features": list(X.columns),
    "minimums": X.min().to_dict(),
    "maximums": X.max().to_dict(),
    "classes": list(best_model.classes_)
}

joblib.dump(model_bundle, "model_bundle.joblib")

print("\n================================")
print("MODEL SUCCESSFULLY SAVED!")
print("================================")

